  "/**",
  " * Finds a parcel anywhere: first active, then historical archive.",
  " */",
  "async function findParcelAnywhere(idOrOrderId) {",
  "  if (!idOrOrderId) return null;",
  "",
  "  let active = null;",
  "  try {",
  "    active = await PostParcel.findOne({",
  "      $or: [{ _id: idOrOrderId }, { orderId: idOrOrderId }]",
  "    }).lean();",
  "  } catch (err) {",
  "    active = await PostParcel.findOne({ orderId: idOrOrderId }).lean();",
  "  }",
  "  if (active) return { ...active, isArchived: false };",
  "",
  "  let history = null;",
  "  try {",
  "    history = await ParcelHistory.findOne({",
  "      $or: [{ originalParcelId: idOrOrderId }, { _id: idOrOrderId }, { orderId: idOrOrderId }]",
  "    })",
  "    .populate('sender', 'firstName lastName email phone profilePhoto walletBalance rating senderPublicId isVerified')",
  "    .populate('acceptedBy', 'firstName lastName email phone profilePhoto walletBalance rating ratingCount travelerPublicId isVerified isOnline')",
  "    .populate('cancelledBy', 'firstName lastName email')",
  "    .lean();",
  "  } catch (err) {",
  "    history = await ParcelHistory.findOne({ orderId: idOrOrderId })",
  "      .populate('sender', 'firstName lastName email phone profilePhoto walletBalance rating senderPublicId isVerified')",
  "      .populate('acceptedBy', 'firstName lastName email phone profilePhoto walletBalance rating ratingCount travelerPublicId isVerified isOnline')",
  "      .populate('cancelledBy', 'firstName lastName email')",
  "      .lean();",
  "  }",
  "",
  "  return history ? adaptHistoryDoc(history) : null;",
