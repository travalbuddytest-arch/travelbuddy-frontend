  "  return {",
  "    parcel: {",
  "      ...parcel,",
  "      fraudScore: fraud.score,",
  "      fraudFlags: fraud.flags,",
  "      progress: progressMap[parcel.status] || (parcel.status === 'delivered' ? 100 : 0)",
  "    },",
  "    walletTransactions: walletTxns,",
  "    conversations: relatedConversations",
  "  };",
  "}",
