  "      .populate('cancelledBy', 'firstName lastName email')",
  "      .populate('adminNotes.adminId', 'firstName lastName email')",
  "      .lean();",
  "  }",
  "",
  "  if (!parcel) {",
  "    let hist = null;",
  "    try {",
  "      hist = await ParcelHistory.findOne({",
  "        $or: [{ originalParcelId: idOrOrderId }, { _id: idOrOrderId }, { orderId: idOrOrderId }]",
  "      })",
  "      .populate('sender', 'firstName lastName email phone profilePhoto walletBalance rating senderPublicId isVerified')",
  "      .populate('acceptedBy', 'firstName lastName email phone profilePhoto walletBalance rating ratingCount travelerPublicId isVerified isOnline')",
  "      .populate('cancelledBy', 'firstName lastName email')",
  "      .lean();",
  "    } catch (e) {",
  "      hist = await ParcelHistory.findOne({ orderId: idOrOrderId })",
  "        .populate('sender', 'firstName lastName email phone profilePhoto walletBalance rating senderPublicId isVerified')",
  "        .populate('acceptedBy', 'firstName lastName email phone profilePhoto walletBalance rating ratingCount travelerPublicId isVerified isOnline')",
  "        .populate('cancelledBy', 'firstName lastName email')",
  "        .lean();",
  "    }",
  "",
  "    if (hist) {",
  "      parcel = adaptHistoryDoc(hist);",
  "    }",
  "  }",
  "",
  "  if (!parcel) return null;",
  "",
  "  const parcelObjId = parcel.originalParcelId || parcel._id;",
