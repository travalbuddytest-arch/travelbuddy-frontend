  "async function getAdminOutcomes({ page = 1, limit = 20, outcome = 'all' }) {",
  "  const pageNum = Math.max(1, parseInt(page, 10) || 1);",
  "  const limitNum = Math.min(100, Math.max(1, parseInt(limit, 10) || 20));",
  "  const skip = (pageNum - 1) * limitNum;",
  "",
  "  const activeStatuses = outcome === 'cancelled' ? ['cancelled']",
  "    : outcome === 'delivered' ? ['delivered']",
  "    : ['cancelled', 'delivered'];",
  "",
  "  const historyFilter = {};",
  "  if (outcome !== 'all') {",
  "    historyFilter.finalStatus = outcome;",
  "  }",
  "",
  "  const [activeRows, activeTotal, historyRows, historyTotal] = await Promise.all([",
  "    PostParcel.find({ status: { $in: activeStatuses } })",
  "      .populate('sender', 'firstName lastName email')",
  "      .populate('cancelledBy', 'firstName lastName email')",
  "      .populate('acceptedBy', 'firstName lastName email')",
  "      .sort({ updatedAt: -1 })",
  "      .limit(pageNum * limitNum)",
  "      .lean(),",
  "    PostParcel.countDocuments({ status: { $in: activeStatuses } }),",
  "    ParcelHistory.find(historyFilter)",
  "      .populate('sender', 'firstName lastName email')",
  "      .populate('cancelledBy', 'firstName lastName email')",
  "      .populate('acceptedBy', 'firstName lastName email')",
  "      .sort({ completedAt: -1 })",
  "      .limit(pageNum * limitNum)",
  "      .lean(),",
  "    ParcelHistory.countDocuments(historyFilter)",
  "  ]);",
  "",
  "  const total = activeTotal + historyTotal;",
  "",
  "  const normalizedActive = activeRows.map(r => ({",
  "    _id: r._id,",
  "    orderId: r.orderId,",
  "    fromCity: r.fromCity,",
  "    toCity: r.toCity,",
  "    sender: r.sender,",
  "    status: r.status,",
  "    outcomeAt: r.status === 'cancelled' ? (r.cancelledAt || r.updatedAt) : (r.deliveredAt || r.updatedAt),",
  "    cancelledBy: r.cancelledBy || null,",
  "    cancellationFee: r.cancellationFee || 0,",
  "    cancellationReason: r.cancellationReason || '',",
  "    traveler: r.acceptedBy || null,",
  "    chargedAmount: r.chargedAmount || r.price || 0,",
  "    travelerEarning: r.travelerEarning || 0,",
  "    isArchived: false",
  "  }));",
  "",
  "  const normalizedHistory = historyRows.map(h => {",
  "    const s = h.snapshot || {};",
  "    return {",
  "      _id: h.originalParcelId || h._id,",
  "      orderId: h.orderId,",
  "      fromCity: s.fromCity || '',",
  "      toCity: s.toCity || '',",
  "      sender: h.sender,",
  "      status: h.finalStatus,",
  "      outcomeAt: h.completedAt || h.updatedAt,",
  "      cancelledBy: h.cancelledBy || null,",
  "      cancellationFee: s.cancellationFee || 0,",
  "      cancellationReason: s.cancellationReason || '',",
  "      traveler: h.acceptedBy || null,",
  "      chargedAmount: s.chargedAmount || s.price || 0,",
  "      travelerEarning: s.travelerEarning || 0,",
  "      isArchived: true",
  "    };",
  "  });",
  "",
  "  const unified = [...normalizedActive, ...normalizedHistory];",
  "  unified.sort((a, b) => new Date(b.outcomeAt || 0).getTime() - new Date(a.outcomeAt || 0).getTime());",
  "",
  "  const paged = unified.slice(skip, skip + limitNum);",
  "",
  "  return {",
  "    outcomes: paged,",
  "    total,",
  "    page: pageNum,",
  "    limit: limitNum,",
  "    totalPages: Math.ceil(total / limitNum) || 1",
  "  };",
  "}",
