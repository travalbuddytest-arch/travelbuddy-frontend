  "/**",
  " * Federates active and archived parcels for admin table view with full filtering and pagination.",
  " */",
  "async function getAdminParcels({ search, status, page = 1, limit = 20, sort = { createdAt: -1 } }) {",
  "  const pageNum = Math.max(1, parseInt(page, 10) || 1);",
  "  const limitNum = Math.min(100, Math.max(1, parseInt(limit, 10) || 20));",
  "  const skip = (pageNum - 1) * limitNum;",
  "",
  "  const activeFilter = {};",
  "  const historyFilter = {};",
  "",
  "  if (status && status !== 'all') {",
  "    if (status === 'delivered') {",
  "      activeFilter.status = 'delivered';",
  "      historyFilter.finalStatus = 'delivered';",
  "    } else if (status === 'cancelled') {",
  "      activeFilter.status = { $regex: /^cancelled/ };",
  "      historyFilter.finalStatus = 'cancelled';",
  "    } else {",
  "      activeFilter.status = status;",
  "      historyFilter.finalStatus = 'NEVER_MATCH';",
  "    }",
  "  }",
  "",
  "  if (search) {",
  "    const escaped = search.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&');",
  "    const regex = { $regex: escaped, $options: 'i' };",
  "",
  "    activeFilter.$or = [",
  "      { orderId: regex },",
  "      { fromCity: regex },",
  "      { toCity: regex },",
  "      { description: regex }",
  "    ];",
  "",
  "    historyFilter.$or = [",
  "      { orderId: regex },",
  "      { 'snapshot.fromCity': regex },",
  "      { 'snapshot.toCity': regex },",
  "      { 'snapshot.description': regex }",
  "    ];",
  "",
  "    const matchingUsers = await User.find({",
  "      $or: [{ firstName: regex }, { lastName: regex }, { email: regex }, { phone: regex }]",
  "    }).select('_id').lean();",
  "",
  "    if (matchingUsers.length > 0) {",
  "      const uIds = matchingUsers.map(u => u._id);",
  "      activeFilter.$or.push({ sender: { $in: uIds } }, { acceptedBy: { $in: uIds } });",
  "      historyFilter.$or.push({ sender: { $in: uIds } }, { acceptedBy: { $in: uIds } });",
  "    }",
  "  }",
  "",
  "  const [activeCount, historyCount] = await Promise.all([",
  "    PostParcel.countDocuments(activeFilter),",
  "    historyFilter.finalStatus === 'NEVER_MATCH' ? 0 : ParcelHistory.countDocuments(historyFilter)",
  "  ]);",
  "",
  "  const total = activeCount + historyCount;",
  "",
  "  const [activeDocs, historyDocs] = await Promise.all([",
  "    PostParcel.find(activeFilter)",
  "      .populate('sender', 'firstName lastName email phone')",
  "      .populate('acceptedBy', 'firstName lastName email phone')",
  "      .sort(sort)",
  "      .limit(pageNum * limitNum)",
  "      .lean(),",
  "    historyFilter.finalStatus === 'NEVER_MATCH' ? [] : ParcelHistory.find(historyFilter)",
  "      .populate('sender', 'firstName lastName email phone')",
  "      .populate('acceptedBy', 'firstName lastName email phone')",
  "      .populate('cancelledBy', 'firstName lastName email phone')",
  "      .sort({ completedAt: -1 })",
  "      .limit(pageNum * limitNum)",
  "      .lean()",
  "  ]);",
  "",
  "  const unified = [",
  "    ...activeDocs.map(d => ({ ...d, isArchived: false })),",
  "    ...historyDocs.map(adaptHistoryDoc)",
  "  ];",
  "",
  "  unified.sort((a, b) => {",
  "    const dateA = new Date(a.createdAt || a.completedAt || 0).getTime();",
  "    const dateB = new Date(b.createdAt || b.completedAt || 0).getTime();",
  "    return dateB - dateA;",
  "  });",
  "",
  "  const paged = unified.slice(skip, skip + limitNum);",
  "",
  "  return {",
  "    parcels: paged,",
  "    total,",
  "    page: pageNum,",
  "    limit: limitNum,",
  "    totalPages: Math.ceil(total / limitNum) || 1",
  "  };",
  "}",
