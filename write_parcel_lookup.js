  "/**",
  " * Returns federated parcel statistics across active and history.",
  " */",
  "async function getAdminParcelStats() {",
  "  const [activeStats, historyDelivered, historyCancelled] = await Promise.all([",
  "    PostParcel.aggregate([",
  "      {",
  "        $group: {",
  "          _id: '$status',",
  "          count: { $sum: 1 }",
  "        }",
  "      }",
  "    ]),",
  "    ParcelHistory.countDocuments({ finalStatus: 'delivered' }),",
  "    ParcelHistory.countDocuments({ finalStatus: 'cancelled' })",
  "  ]);",
  "",
  "  const map = {",
  "    pending: 0,",
  "    accepted: 0,",
  "    pickup_confirmed: 0,",
  "    in_transit: 0,",
  "    delivered: historyDelivered,",
  "    cancelled: historyCancelled",
  "  };",
  "",
  "  activeStats.forEach(s => {",
  "    if (s._id === 'delivered') map.delivered += s.count;",
  "    else if (s._id === 'cancelled') map.cancelled += s.count;",
  "    else if (map.hasOwnProperty(s._id)) map[s._id] = s.count;",
  "  });",
  "",
  "  return map;",
  "}",
